let language = 'vi'
try { if (localStorage.getItem('ferry-language') === 'en') language = 'en' } catch {}
export const getLanguage = () => language
export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'vi'
  try { localStorage.setItem('ferry-language', language) } catch {}
  document.documentElement.lang = language
  document.title = t('Lái Đò Tri Thức')
}
export const t = text => language === 'en' ? (translations[text] ?? text) : text

// Translate only source text in template segments. Interpolated names and data
// are never searched or replaced, even when a student is called “Nam” or “Vừa”.
const exactOnly = new Set(['bật', 'tắt', 'Nam', 'Nữ', 'Cô', 'Thầy', 'Nhanh', 'Vừa', 'Hồi hộp', 'hiện', 'ẩn'])
const phrases = Object.keys(translations).filter(key => !exactOnly.has(key)).sort((a, b) => b.length - a.length)
const pattern = new RegExp(phrases.map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g')
export function tr(strings, ...values) {
  return strings.reduce((result, part, index) => result + (language === 'en' ? part.replace(pattern, match => translations[match]) : part) + (index < values.length ? values[index] : ''), '')
}
export function classLabel(name) {
  if (language !== 'en') return name
  return name === 'Lớp mẫu' || name === 'Lớp học' ? t(name) : name.replace(/^Lớp (\d+)$/, 'Class $1')
}
setLanguage(language)
