import { test, expect } from '@playwright/test'

async function singleStudent(page, name, gender, teacher) {
  await page.clock.install({ time: new Date('2026-11-10T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-11-10T00:00:01Z'))
  await page.goto('http://127.0.0.1:5180')
  await page.locator('[data-action="add-class"]').click()
  if (gender === 'Nữ') await page.locator('[data-action="gender"]').click()
  await page.locator('#student-name').fill(name)
  await page.locator('[data-action="add-student"]').click()
  await page.getByRole('button', { name: teacher, exact: true }).click()
  await page.getByRole('button', { name: 'Nhanh', exact: true }).click()
  await page.locator('[data-action="launch"]').click()
  await expect(page.locator('.passenger')).toHaveCount(1)
}

test('the home screen shows and remembers the teacher choice without clearing input', async ({ page }) => {
  await page.goto('http://127.0.0.1:5180')
  await expect(page.getByRole('group', { name: 'Chọn người lái đò' })).toBeInViewport()
  await page.locator('#student-name').fill('Tên đang nhập')
  const male = page.getByRole('button', { name: 'Thầy', exact: true })
  await male.click()
  await expect(male).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Cô', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('#student-name')).toHaveValue('Tên đang nhập')
  await expect(page.locator('[data-teacher-portrait="male"]')).toHaveAttribute('src', /^data:image\/png/)
  await page.screenshot({ path: 'tmp/teacher-selection.png' })
  await page.reload()
  await expect(male).toHaveAttribute('aria-pressed', 'true')
  await page.locator('[data-action="launch"]').click()
  await expect(page.locator('.teacher-animated')).toHaveAttribute('data-teacher-kind', 'male')
  await page.getByRole('button', { name: 'Dừng', exact: true }).click()
  await page.getByRole('button', { name: 'Cô', exact: true }).click()
  await page.locator('[data-action="launch"]').click()
  await expect(page.locator('.teacher-animated')).toHaveAttribute('data-teacher-kind', 'female')
  await page.getByRole('button', { name: 'Dừng', exact: true }).click()
})

for (const [name, gender, teacher, key] of [['Trần Gia Bảo', 'Nam', 'Thầy', 'boy'], ['Trịnh Gia Hân', 'Nữ', 'Cô', 'girl']]) {
  test(`${key} winner sleeps, wakes, stands in the spotlight, then appears on the board`, async ({ page }) => {
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await singleStudent(page, name, gender, teacher)
    if (key === 'boy') await page.locator('[data-game="names"]').click()
    await page.clock.runFor(7300)
    const scene = page.locator('.game'), winner = page.locator('.winner-student')
    await expect(scene).toHaveAttribute('data-finale-stage', 'sleeping')
    await expect(winner).toHaveCount(1)
    await expect(winner).toHaveAttribute('data-student-state', 'sleeping')
    await expect(page.locator('.winner-glow')).toBeVisible()
    await expect(winner.locator('.passenger-name')).toBeVisible()
    await expect(page.locator('.result-overlay')).toHaveCount(0)
    await expect.poll(() => page.locator('.winner-vignette').evaluate(node => Number(getComputedStyle(node).opacity))).toBe(1)
    const sleeping = await winner.locator('.seated-sprite').getAttribute('src')
    const identity = await winner.getAttribute('data-character-variant')
    await page.screenshot({ path: `tmp/winner-${key}-sleeping.png` })

    await page.clock.runFor(1500)
    await expect(scene).toHaveAttribute('data-finale-stage', 'waking')
    await expect(winner).toHaveAttribute('data-student-state', 'waking')
    await expect(winner).not.toHaveClass(/sleepy-student/)
    expect(await winner.locator('.seated-sprite').getAttribute('src')).not.toBe(sleeping)
    await expect(page.locator('.winner-dialog')).toHaveText('Ơ… tới bờ rồi ạ?')
    await page.screenshot({ path: `tmp/winner-${key}-waking.png` })

    await page.clock.runFor(700)
    await expect(scene).toHaveAttribute('data-finale-stage', 'awake')
    await expect(winner).toHaveAttribute('data-character-variant', identity)
    await expect(page.locator('.winner-dialog')).toHaveText('Dạ… em dậy rồi ạ!')
    await expect(page.locator('.result-overlay')).toHaveCount(0)
    await page.screenshot({ path: `tmp/winner-${key}-awake.png` })

    await page.clock.runFor(1300)
    await expect(scene).toHaveAttribute('data-finale-stage', 'revealed')
    await expect(page.locator('.result-overlay')).toBeVisible()
    await expect(page.locator('.chalkboard h2')).toHaveText(name)
    await expect(page.locator('.winner-vignette')).toHaveCount(0)
    await page.getByRole('button', { name: 'Sửa danh sách', exact: true }).click()
    await expect(page.locator('.winner-glow,.winner-dialog')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}

test('stopping during the spotlight cancels the wake-up and result', async ({ page }) => {
  await singleStudent(page, 'Lê Minh An', 'Nam', 'Cô')
  await page.clock.runFor(7300)
  await expect(page.locator('.winner-vignette')).toBeVisible()
  await page.getByRole('button', { name: 'Dừng', exact: true }).click()
  await page.clock.runFor(6000)
  await expect(page.locator('.winner-vignette,.winner-glow,.result-overlay')).toHaveCount(0)
  await expect(page.locator('[data-action="launch"]')).toBeVisible()
})
