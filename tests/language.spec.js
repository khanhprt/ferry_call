import { test, expect } from '@playwright/test'

test('language choice preserves names and drafts, translates controls, and persists', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5180')
  const fonts = await page.locator('.brand h1').evaluate(el => getComputedStyle(el).fontFamily)
  await page.locator('#student-name').fill('Nam')
  await page.locator('#bulk-names').fill('Nguyễn Minh Anh\nVừa')
  await page.locator('#language').selectOption('en')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page).toHaveTitle('The Knowledge Ferry')
  await expect(page.locator('#student-name')).toHaveValue('Nam')
  await expect(page.locator('#bulk-names')).toHaveValue('Nguyễn Minh Anh\nVừa')
  await expect(page.locator('.notice')).toContainText('Try this sample class')
  await expect(page.locator('[data-teacher="Thầy"]')).toContainText('Male teacher')
  await expect(page.locator('.student-name').first()).toHaveText('Nguyễn Minh Anh')
  expect(await page.locator('.brand h1').evaluate(el => getComputedStyle(el).fontFamily)).toBe(fonts)
  await page.locator('[data-action="bulk-add"]').click()
  await expect(page.locator('.student-name')).toHaveText(['Nguyễn Minh Anh', 'Vừa'])
  await page.reload()
  await expect(page.locator('#language')).toHaveValue('en')
  await expect(page.locator('.attendance').first()).toHaveText('Present')
  await page.screenshot({ path: 'tmp/home-english.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('#language')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'tmp/home-english-mobile.png', fullPage: true })
  await page.locator('#language').selectOption('vi')
  await expect(page.locator('.brand h1')).toHaveText('Lái Đò Tri Thức')
  await expect(page.locator('.student-name')).toHaveText(['Nguyễn Minh Anh', 'Vừa'])
  expect(errors).toEqual([])
})

test('English journey and finale keep the selected student name intact', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install({ time: new Date('2026-11-10T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-11-10T00:00:01Z'))
  await page.goto('http://127.0.0.1:5180')
  await page.locator('#language').selectOption('en')
  await page.locator('[data-action="add-class"]').click()
  await expect(page.locator('.empty')).toContainText('The ferry is waiting for you')
  await page.locator('#student-name').fill('Nam')
  await page.locator('[data-action="add-student"]').click()
  await page.locator('[data-teacher="Thầy"]').click()
  await page.locator('[data-speed="Nhanh"]').click()
  await page.locator('[data-action="launch"]').click()
  await expect(page.locator('.game')).toBeVisible()
  await expect(page.locator('.speech')).toHaveText('Mr. is ready. Let’s go!')
  await expect(page.locator('.passenger-name')).toHaveText('Nam')
  await expect(page.locator('[data-game="names"]')).toHaveText('Names: shown')
  await page.locator('[data-game="sound"]').click()
  await expect(page.locator('[data-game="sound"]')).toHaveText('Sound: off')
  await page.clock.runFor(14000)
  await expect(page.locator('.result-overlay')).toBeVisible()
  await expect(page.locator('.chalkboard h2')).toHaveText('Nam')
  await expect(page.locator('.board-intro')).toHaveText('AND THE LUCKY PASSENGER IS')
  await expect(page.locator('.board-small')).toHaveText('What a lovely ferry journey!')
  await expect(page.locator('[data-game="again"]')).toHaveText('New journey')
  await page.screenshot({ path: 'tmp/result-english.png' })
  expect(errors).toEqual([])
})
